import { BattlePreset, UnitSnapshot } from '../types';

function line(
  catalogId: string,
  team: 'red' | 'blue' | 'ffa' | 'neutral',
  x: number,
  zStart: number,
  zEnd: number,
  count: number,
  extra: Partial<UnitSnapshot> = {}
): UnitSnapshot[] {
  const out: UnitSnapshot[] = [];
  for (let i = 0; i < count; i++) {
    const t = count === 1 ? 0.5 : i / (count - 1);
    out.push({
      catalogId,
      team,
      ai: extra.ai ?? 'aggressive',
      x,
      z: zStart + (zEnd - zStart) * t,
      scale: extra.scale ?? 1,
      hpMult: extra.hpMult ?? 1,
      dmgMult: extra.dmgMult ?? 1,
      spdMult: extra.spdMult ?? 1,
      traits: extra.traits,
    });
  }
  return out;
}

function grid(
  catalogId: string,
  team: 'red' | 'blue' | 'ffa' | 'neutral',
  cx: number,
  cz: number,
  cols: number,
  rows: number,
  spacing: number,
  extra: Partial<UnitSnapshot> = {}
): UnitSnapshot[] {
  const out: UnitSnapshot[] = [];
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      out.push({
        catalogId,
        team,
        ai: extra.ai ?? 'aggressive',
        x: cx + (c - (cols - 1) / 2) * spacing,
        z: cz + (r - (rows - 1) / 2) * spacing,
        scale: extra.scale ?? 1,
        hpMult: extra.hpMult ?? 1,
        dmgMult: extra.dmgMult ?? 1,
        spdMult: extra.spdMult ?? 1,
        traits: extra.traits,
      });
    }
  }
  return out;
}

