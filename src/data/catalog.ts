export const CATALOG_MAP: Map<string, CatalogItem> = new Map(CATALOG.map((item) => [item.id, item]));

export function getCatalogForMode(mode: RenderStyle): CatalogItem[] {
  const pool = mode === 'hybrid' ? [...CATALOG] : CATALOG.filter((item) => item.modes.includes(mode));
  return pool.sort((a, b) => b.powerScore - a.powerScore || b.hp - a.hp);
}

/**
 * Finds the authentic native 3D equivalent of a unit when switching graphic modes
 * (e.g. Ultra Realistic Plate Knight <-> Stylized Knight <-> Manga Samurai <-> Voxel Knight).
 * In 'hybrid' (Karma) mode every 3D asset is preserved as-is!
 */
export function findModeEquivalent(catalogId: string, targetMode: RenderStyle): CatalogItem | null {
  const cur = CATALOG_MAP.get(catalogId);
  if (!cur) return null;
  if (targetMode === 'hybrid' || cur.modes.includes(targetMode)) return cur;

  const modePool = getCatalogForMode(targetMode);
  if (cur.archetype) {
    const exact = modePool.find((c) => c.archetype === cur.archetype);
    if (exact) return exact;
  }
  // Fallback: match combatStyle + category
  const sameStyle = modePool.find((c) => c.combatStyle === cur.combatStyle && !c.isStructure === !cur.isStructure);
  if (sameStyle) return sameStyle;
  return modePool.find((c) => !c.isStructure) ?? modePool[0] ?? null;
}

